"""Compatibility wrapper for the canonical application entry point.

This file exists to avoid the duplicate-app confusion noted during analysis.
It reuses the real Flask app from the project root instead of launching a second,
separate implementation.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app import app

if __name__ == "__main__":
    host = os.getenv("HOST", "127.0.0.1")
    port = int(os.getenv("PORT", "5000"))
    app.run(host=host, port=port, debug=False, threaded=True)
